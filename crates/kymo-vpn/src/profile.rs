//! Text the gateway and the players receive: the OpenVPN server config, per player address
//! files, and the `.ovpn` profile. Hosts and names are validated because they end up in
//! config files, where a newline would add an arbitrary directive.

use std::net::Ipv4Addr;

use crate::addressing::{Ipv4Net, TunnelPool};
use crate::error::VpnError;

/// Where the gateway container sees the directory the platform writes to.
pub const MOUNT: &str = "/vpn";
/// The UDP port OpenVPN listens on inside the container.
pub const INNER_PORT: u16 = 1194;
/// The management console address used to disconnect a player.
pub const MANAGEMENT_PORT: u16 = 7505;

/// The server config. `lab_pool` is pushed to every client as one route; what a player may
/// actually reach is decided by the gateway firewall, not by routing.
pub fn server_conf(tunnel: &TunnelPool, lab_pool: &Ipv4Net) -> String {
    let t = tunnel.net();
    format!(
        "\
# Generated by Kymo. Do not edit: it is rewritten when the server starts.
port {INNER_PORT}
proto udp
dev tun
topology subnet
server {} {}
ca {MOUNT}/pki/ca.crt
cert {MOUNT}/pki/server.crt
key {MOUNT}/pki/server.key
dh none
tls-crypt {MOUNT}/pki/ta.key
crl-verify {MOUNT}/pki/crl.pem
tls-version-min 1.2
remote-cert-tls client
data-ciphers AES-256-GCM:CHACHA20-POLY1305
client-config-dir {MOUNT}/ccd
ccd-exclusive
push \"route {} {}\"
keepalive 10 60
explicit-exit-notify 1
persist-key
persist-tun
disable-dco
management 127.0.0.1 {MANAGEMENT_PORT}
verb 3
",
        t.network(),
        t.netmask(),
        lab_pool.network(),
        lab_pool.netmask(),
    )
}

/// The per player file that must exist for a player to connect (`ccd-exclusive`): it gives
/// the player a fixed tunnel address. Removing the file stops new connections.
pub fn client_config(tunnel_ip: Ipv4Addr, tunnel: &TunnelPool) -> String {
    format!("ifconfig-push {tunnel_ip} {}\n", tunnel.net().netmask())
}

/// A name that is safe in a file name, a config file and a shell word.
pub fn valid_common_name(cn: &str) -> bool {
    !cn.is_empty()
        && cn.len() <= 64
        && cn
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
        && !cn.starts_with('-')
}

/// A DNS name or IPv4 address players connect to.
pub fn valid_remote_host(host: &str) -> bool {
    if host.is_empty() || host.len() > 253 {
        return false;
    }
    if host.parse::<Ipv4Addr>().is_ok() {
        return true;
    }
    host.split('.').all(|label| {
        !label.is_empty()
            && label.len() <= 63
            && !label.starts_with('-')
            && !label.ends_with('-')
            && label.chars().all(|c| c.is_ascii_alphanumeric() || c == '-')
    })
}

pub struct ClientProfile<'a> {
    pub remote_host: &'a str,
    pub remote_port: u16,
    pub ca_pem: &'a str,
    pub cert_pem: &'a str,
    pub key_pem: &'a str,
    pub tls_crypt_key: &'a str,
}

/// The `.ovpn` file, with every secret inline so one file is all a player needs.
pub fn client_profile(p: &ClientProfile<'_>) -> Result<String, VpnError> {
    if !valid_remote_host(p.remote_host) {
        return Err(VpnError::Profile("the VPN host name is not valid".into()));
    }
    if p.remote_port == 0 {
        return Err(VpnError::Profile("the VPN port is not valid".into()));
    }
    for (what, pem, marker) in [
        ("CA certificate", p.ca_pem, "-----BEGIN CERTIFICATE-----"),
        ("certificate", p.cert_pem, "-----BEGIN CERTIFICATE-----"),
        ("private key", p.key_pem, "-----BEGIN PRIVATE KEY-----"),
        (
            "tls-crypt key",
            p.tls_crypt_key,
            "-----BEGIN OpenVPN Static key V1-----",
        ),
    ] {
        if !pem.contains(marker) || pem.contains("</") {
            return Err(VpnError::Profile(format!("the {what} is not valid PEM")));
        }
    }
    Ok(format!(
        "\
# Kymo VPN profile. Keep this file private: it is your key to your own lab network.
client
dev tun
proto udp
remote {} {}
resolv-retry infinite
nobind
persist-key
persist-tun
remote-cert-tls server
tls-version-min 1.2
data-ciphers AES-256-GCM:CHACHA20-POLY1305
verb 3
<ca>
{}</ca>
<cert>
{}</cert>
<key>
{}</key>
<tls-crypt>
{}</tls-crypt>
",
        p.remote_host,
        p.remote_port,
        with_newline(p.ca_pem),
        with_newline(p.cert_pem),
        with_newline(p.key_pem),
        with_newline(p.tls_crypt_key),
    ))
}

fn with_newline(text: &str) -> String {
    let mut out = text.trim_end().to_owned();
    out.push('\n');
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::pki::{Ca, generate_tls_crypt_key};

    fn tunnel() -> TunnelPool {
        TunnelPool::new("10.8.0.0/16".parse().unwrap()).unwrap()
    }

    #[test]
    fn the_server_config_pins_down_every_security_relevant_option() {
        let conf = server_conf(&tunnel(), &"10.77.0.0/16".parse().unwrap());
        for line in [
            "server 10.8.0.0 255.255.0.0",
            "push \"route 10.77.0.0 255.255.0.0\"",
            "ccd-exclusive",
            "client-config-dir /vpn/ccd",
            "crl-verify /vpn/pki/crl.pem",
            "tls-crypt /vpn/pki/ta.key",
            "remote-cert-tls client",
            "tls-version-min 1.2",
            "disable-dco",
            "management 127.0.0.1 7505",
        ] {
            assert!(conf.lines().any(|l| l == line), "missing {line:?}");
        }
        assert!(
            !conf.contains("client-to-client"),
            "players must not talk to each other"
        );
        assert!(
            !conf.contains("redirect-gateway"),
            "players keep their own internet"
        );
    }

    #[test]
    fn a_client_config_gives_a_fixed_address() {
        assert_eq!(
            client_config(Ipv4Addr::new(10, 8, 3, 9), &tunnel()),
            "ifconfig-push 10.8.3.9 255.255.0.0\n"
        );
    }

    #[test]
    fn names_and_hosts_that_could_inject_config_are_refused() {
        for ok in ["u42", "a-b-9"] {
            assert!(valid_common_name(ok), "{ok}");
        }
        for bad in [
            "",
            "-x",
            "U1",
            "a b",
            "a\nb",
            "../x",
            "a/b",
            "x;y",
            &"a".repeat(65),
        ] {
            assert!(!valid_common_name(bad), "{bad:?}");
        }
        for ok in ["vpn.example.org", "203.0.113.9", "localhost", "a-b.c"] {
            assert!(valid_remote_host(ok), "{ok}");
        }
        for bad in [
            "",
            "a b",
            "x\nremote evil 1",
            "a..b",
            "-a.b",
            "a.b-",
            "a_b",
            "http://x",
            "x:1194",
            &"a".repeat(254),
        ] {
            assert!(!valid_remote_host(bad), "{bad:?}");
        }
    }

    #[test]
    fn the_profile_holds_everything_inline_and_nothing_extra() {
        let ca = Ca::load(Ca::generate(1_800_000_000, 365).unwrap()).unwrap();
        let client = ca.issue_client("u1", 1_800_000_000, 30).unwrap();
        let ta = generate_tls_crypt_key();
        let profile = client_profile(&ClientProfile {
            remote_host: "vpn.example.org",
            remote_port: 1194,
            ca_pem: ca.cert_pem(),
            cert_pem: &client.cert_pem,
            key_pem: &client.key_pem,
            tls_crypt_key: &ta,
        })
        .unwrap();
        for needle in [
            "remote vpn.example.org 1194",
            "remote-cert-tls server",
            "<ca>",
            "</tls-crypt>",
            "BEGIN PRIVATE KEY",
            "BEGIN OpenVPN Static key V1",
        ] {
            assert!(profile.contains(needle), "{needle}");
        }
        assert_eq!(profile.matches("BEGIN PRIVATE KEY").count(), 1);
        assert!(!profile.contains("redirect-gateway"));
        assert!(
            !profile.contains("disable-dco"),
            "older clients do not know this option"
        );
        // The CA key must never be in a profile.
        let ca_key_marker = Ca::generate(1_800_000_000, 1).unwrap().key_pem;
        assert!(!profile.contains(ca_key_marker.lines().nth(1).unwrap_or("x")));
    }

    #[test]
    fn the_profile_rejects_a_bad_host_port_or_pem() {
        let base = ClientProfile {
            remote_host: "vpn.example.org",
            remote_port: 1194,
            ca_pem: "-----BEGIN CERTIFICATE-----\nx\n-----END CERTIFICATE-----\n",
            cert_pem: "-----BEGIN CERTIFICATE-----\nx\n-----END CERTIFICATE-----\n",
            key_pem: "-----BEGIN PRIVATE KEY-----\nx\n-----END PRIVATE KEY-----\n",
            tls_crypt_key: "-----BEGIN OpenVPN Static key V1-----\nx\n-----END OpenVPN Static key V1-----\n",
        };
        assert!(client_profile(&base).is_ok());
        assert!(
            client_profile(&ClientProfile {
                remote_host: "a\nremote x 1",
                ..base
            })
            .is_err()
        );
        let base = ClientProfile {
            remote_host: "h.example",
            ..base
        };
        assert!(
            client_profile(&ClientProfile {
                remote_port: 0,
                ..base
            })
            .is_err()
        );
        let injected =
            "-----BEGIN CERTIFICATE-----\n</ca>\nremote evil 1\n-----END CERTIFICATE-----\n";
        assert!(
            client_profile(&ClientProfile {
                ca_pem: injected,
                ..base
            })
            .is_err()
        );
        assert!(
            client_profile(&ClientProfile {
                key_pem: "not a key",
                ..base
            })
            .is_err()
        );
    }
}
