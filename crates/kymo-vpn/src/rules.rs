//! The gateway firewall. Default deny; one pair of rules per (player, lab) that is allowed.
//! Built only from typed addresses, never from free text, so it cannot be steered by input.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::net::Ipv4Addr;

use crate::addressing::Ipv4Net;

/// One player is allowed to reach one lab network.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct Allow {
    pub client: Ipv4Addr,
    pub lab: Ipv4Net,
}

/// A script that (re)creates the Kymo firewall chain. Safe to run any number of times: it
/// flushes the chain, so for a moment nothing is allowed, which is the safe direction.
pub fn firewall_script(allows: &[Allow], tunnel: &Ipv4Net, lab_pool: &Ipv4Net) -> String {
    let unique: BTreeSet<&Allow> = allows.iter().collect();
    let mut s = String::from(
        "#!/bin/sh\n# Generated by Kymo. Rewritten whenever a lab or a player changes.\nset -e\n",
    );
    s.push_str("iptables -P FORWARD DROP\n");
    s.push_str("iptables -N KYMO_FWD 2>/dev/null || true\n");
    s.push_str("iptables -F KYMO_FWD\n");
    s.push_str(
        "iptables -C FORWARD -j KYMO_FWD 2>/dev/null || iptables -I FORWARD 1 -j KYMO_FWD\n",
    );
    for a in unique {
        let _ = writeln!(
            s,
            "iptables -A KYMO_FWD -s {} -d {} -j ACCEPT",
            a.client, a.lab
        );
        let _ = writeln!(
            s,
            "iptables -A KYMO_FWD -s {} -d {} -j ACCEPT",
            a.lab, a.client
        );
    }
    s.push_str("iptables -A KYMO_FWD -j DROP\n");
    let _ = writeln!(
        s,
        "iptables -t nat -C POSTROUTING -s {tunnel} -d {lab_pool} -j MASQUERADE 2>/dev/null || iptables -t nat -A POSTROUTING -s {tunnel} -d {lab_pool} -j MASQUERADE"
    );
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    fn nets() -> (Ipv4Net, Ipv4Net) {
        (
            "10.8.0.0/16".parse().unwrap(),
            "10.77.0.0/16".parse().unwrap(),
        )
    }

    fn allow(client: [u8; 4], lab: &str) -> Allow {
        Allow {
            client: Ipv4Addr::from(client),
            lab: lab.parse().unwrap(),
        }
    }

    #[test]
    fn with_no_players_nothing_is_allowed() {
        let (t, p) = nets();
        let script = firewall_script(&[], &t, &p);
        assert!(script.contains("iptables -P FORWARD DROP"));
        assert!(script.contains("iptables -A KYMO_FWD -j DROP"));
        assert_eq!(script.matches("-j ACCEPT").count(), 0);
    }

    #[test]
    fn each_pair_gets_a_rule_in_both_directions_and_the_drop_comes_last() {
        let (t, p) = nets();
        let script = firewall_script(
            &[
                allow([10, 8, 0, 2], "10.77.0.0/27"),
                allow([10, 8, 0, 3], "10.77.0.32/27"),
            ],
            &t,
            &p,
        );
        for rule in [
            "iptables -A KYMO_FWD -s 10.8.0.2 -d 10.77.0.0/27 -j ACCEPT",
            "iptables -A KYMO_FWD -s 10.77.0.0/27 -d 10.8.0.2 -j ACCEPT",
            "iptables -A KYMO_FWD -s 10.8.0.3 -d 10.77.0.32/27 -j ACCEPT",
            "iptables -A KYMO_FWD -s 10.77.0.32/27 -d 10.8.0.3 -j ACCEPT",
        ] {
            assert!(script.lines().any(|l| l == rule), "{rule}");
        }
        assert!(
            !script.contains("-s 10.8.0.2 -d 10.77.0.32/27"),
            "no cross access"
        );
        let lines: Vec<&str> = script.lines().collect();
        let drop = lines
            .iter()
            .position(|l| *l == "iptables -A KYMO_FWD -j DROP")
            .unwrap();
        let last_accept = lines
            .iter()
            .rposition(|l| l.ends_with("-j ACCEPT"))
            .unwrap();
        assert!(drop > last_accept, "the catch-all drop closes the chain");
    }

    #[test]
    fn a_team_shares_a_lab_and_duplicates_collapse() {
        let (t, p) = nets();
        let a = allow([10, 8, 0, 2], "10.77.0.0/27");
        let b = allow([10, 8, 0, 9], "10.77.0.0/27");
        let script = firewall_script(&[a, b, a, b], &t, &p);
        assert_eq!(script.matches("-j ACCEPT").count(), 4);
    }

    #[test]
    fn output_is_deterministic_and_nat_covers_only_tunnel_to_labs() {
        let (t, p) = nets();
        let x = [
            allow([10, 8, 0, 3], "10.77.0.32/27"),
            allow([10, 8, 0, 2], "10.77.0.0/27"),
        ];
        let y = [x[1], x[0]];
        assert_eq!(firewall_script(&x, &t, &p), firewall_script(&y, &t, &p));
        let script = firewall_script(&x, &t, &p);
        assert!(script.contains("-s 10.8.0.0/16 -d 10.77.0.0/16 -j MASQUERADE"));
        assert_eq!(
            script.matches("MASQUERADE").count(),
            2,
            "one check, one add"
        );
    }
}
